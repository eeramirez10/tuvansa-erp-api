import { Router } from 'express';
import type { PurchaseOrdersController } from './purchase-orders-controller.js';

export const createPurchaseOrdersRouter = (controller: PurchaseOrdersController): Router => {
  const router = Router();
  router.get('/', controller.search);
  router.post('/', controller.create);
  router.get('/create', controller.getCreation);
  router.get('/create/suppliers', controller.searchCreationSuppliers);
  router.get('/create/products', controller.searchCreationProducts);
  router.get('/authorization/suppliers', controller.searchAuthorizationSuppliers);
  router.get('/by-number/:purchaseOrderNumber', controller.getByNumberHandler);
  router.get('/:purchaseOrderId/previous', controller.previous);
  router.get('/:purchaseOrderId/next', controller.next);
  router.get('/:purchaseOrderId/actions/auxiliar', controller.panel('receipts'));
  router.get('/:purchaseOrderId/actions/classifications', controller.panel('classifications'));
  router.patch('/:purchaseOrderId/actions/classifications', controller.classify);
  router.get('/:purchaseOrderId/actions/confirmation', controller.getConfirmation);
  router.patch('/:purchaseOrderId/actions/confirmation', controller.confirm);
  router.get('/:purchaseOrderId/actions/quote-conversion', controller.getConversion);
  router.patch('/:purchaseOrderId/actions/quote-conversion', controller.convert);
  router.get('/:purchaseOrderId/actions/authorization', controller.getAuthorization);
  router.patch('/:purchaseOrderId/actions/authorization', controller.authorize);
  router.patch('/:purchaseOrderId/actions/authorization/supplier', controller.changeSupplier('authorization'));
  router.get('/:purchaseOrderId/actions/change-supplier', controller.getSupplierAction);
  router.patch('/:purchaseOrderId/actions/change-supplier', controller.changeSupplier('action'));
  router.get('/:purchaseOrderId/actions/comments', controller.panel('comments'));
  router.get('/:purchaseOrderId/actions/comments/editor', controller.getCommentsEditor);
  router.patch('/:purchaseOrderId/actions/comments', controller.saveComments);
  router.get('/:purchaseOrderId/actions/duplicate', controller.getDuplicate);
  router.post('/:purchaseOrderId/actions/duplicate', controller.duplicate);
  router.get('/:purchaseOrderId/actions/split', controller.getSplit);
  router.post('/:purchaseOrderId/actions/split', controller.split);
  router.get('/:purchaseOrderId/actions/branches', controller.getBranchTransfer);
  router.post('/:purchaseOrderId/actions/branches', controller.saveBranchTransfer);
  router.get('/:purchaseOrderId/actions/ct', controller.panel('ct'));
  router.get('/:purchaseOrderId/actions/ct/editor', controller.getColorSizeEditor);
  router.patch('/:purchaseOrderId/actions/ct', controller.saveColorSize);
  router.get('/:purchaseOrderId/actions/pieces', controller.panel('pieces'));
  router.get('/:purchaseOrderId/actions/pieces/editor', controller.getPiecesEditor);
  router.patch('/:purchaseOrderId/actions/pieces', controller.savePieces);
  router.get('/:purchaseOrderId/actions/pieces/confirmation', controller.getPieceConfirmation);
  router.patch('/:purchaseOrderId/actions/pieces/confirmation', controller.savePieceConfirmation);
  router.get('/:purchaseOrderId/edit', controller.getEditor);
  router.get('/:purchaseOrderId/edit/products', controller.searchEditorProducts);
  router.get('/:purchaseOrderId/removal', controller.getRemoval);
  router.delete('/:purchaseOrderId', controller.remove);
  router.patch('/:purchaseOrderId', controller.saveEdition);
  router.get('/:purchaseOrderId', controller.getById);
  return router;
};
